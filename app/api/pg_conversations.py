"""Opt-in PostgreSQL conversation and memory outbox store.

The repository is owner scoped. The two outboxes are committed in the same
transaction as their source turn or conversation deletion. A separate
connection per repository permits multiple API processes to share one store.
"""

import json
import threading
from contextlib import contextmanager
from datetime import datetime, timedelta, timezone
from uuid import uuid4

import psycopg
from psycopg import sql
from psycopg.rows import dict_row

from app.api.conversations import render_conversation
from app.api.documents import DocumentRepository
from app.security.policy import Subject


SCHEMA_SQL = """
CREATE TABLE IF NOT EXISTS conversation_schema_version (version integer NOT NULL);
CREATE TABLE IF NOT EXISTS conversations (
    id text PRIMARY KEY, org_id text NOT NULL, owner_id text NOT NULL,
    title text NOT NULL, updated_at text NOT NULL
);
CREATE INDEX IF NOT EXISTS conversations_owner
    ON conversations(org_id, owner_id, updated_at DESC);
CREATE TABLE IF NOT EXISTS conversation_turns (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id text NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    question text NOT NULL, mode text NOT NULL, answer_json text NOT NULL,
    workflow_run_id text
);
CREATE INDEX IF NOT EXISTS turns_conversation
    ON conversation_turns(conversation_id, id);
CREATE UNIQUE INDEX IF NOT EXISTS turns_workflow_run
    ON conversation_turns(workflow_run_id) WHERE workflow_run_id IS NOT NULL;
CREATE TABLE IF NOT EXISTS conversation_delete_outbox (
    id text PRIMARY KEY, org_id text NOT NULL, owner_id text NOT NULL,
    conversation_id text NOT NULL, created_at text NOT NULL,
    available_at text NOT NULL, delivered_at text,
    lease_token text, lease_until text,
    attempts integer NOT NULL DEFAULT 0, last_error_code text
);
CREATE INDEX IF NOT EXISTS conversation_delete_outbox_ready
    ON conversation_delete_outbox(delivered_at, available_at, created_at);
CREATE TABLE IF NOT EXISTS conversation_memory_outbox (
    id text PRIMARY KEY, org_id text NOT NULL, owner_id text NOT NULL,
    conversation_id text NOT NULL, turn_id bigint NOT NULL,
    include_ordinary integer NOT NULL, created_at text NOT NULL,
    available_at text NOT NULL, delivered_at text,
    lease_token text, lease_until text,
    attempts integer NOT NULL DEFAULT 0, last_error_code text
);
CREATE INDEX IF NOT EXISTS conversation_memory_outbox_ready
    ON conversation_memory_outbox(delivered_at, available_at, created_at);
"""


def _now() -> datetime:
    return datetime.now(timezone.utc)


def _stamp(value: datetime) -> str:
    return value.isoformat(timespec="microseconds")


class PgConversationRepository:
    enable_delete_outbox = True

    def __init__(self, dsn: str, *, schema: str = "memory", create_schema: bool = False):
        if not dsn:
            raise ValueError("CONVERSATION_DATABASE_URL_REQUIRED")
        self._lock = threading.RLock()
        self.dsn = dsn
        self.schema = schema
        self._connection = self._open_connection()
        if create_schema:
            self.create_schema()
        else:
            self.check_schema()

    def _open_connection(self):
        connection = psycopg.connect(
            self.dsn, row_factory=dict_row, autocommit=True, connect_timeout=3)
        connection.execute(sql.SQL("SET search_path TO {}").format(
            sql.Identifier(self.schema)))
        return connection

    @property
    def connection(self):
        with self._lock:
            if self._connection.closed:
                self._connection = self._open_connection()
            return self._connection

    def create_schema(self) -> None:
        with self._lock, self.connection.transaction():
            self.connection.execute(sql.SQL("CREATE SCHEMA IF NOT EXISTS {}").format(
                sql.Identifier(self.schema)))
            self.connection.execute(sql.SQL("SET LOCAL search_path TO {}").format(
                sql.Identifier(self.schema)))
            self.connection.execute(SCHEMA_SQL)
            row = self.connection.execute(
                "SELECT version FROM conversation_schema_version").fetchone()
            if row is None:
                self.connection.execute("INSERT INTO conversation_schema_version VALUES (1)")
            elif row["version"] != 1:
                raise RuntimeError("UNSUPPORTED_CONVERSATION_SCHEMA")

    def check_schema(self) -> None:
        with self._lock:
            try:
                versions = self.connection.execute(
                    "SELECT version FROM conversation_schema_version").fetchall()
            except psycopg.errors.UndefinedTable as exc:
                raise RuntimeError("CONVERSATION_SCHEMA_MISSING") from exc
            if len(versions) != 1 or versions[0]["version"] != 1:
                raise RuntimeError("UNSUPPORTED_CONVERSATION_SCHEMA")

    def close(self) -> None:
        with self._lock:
            self._connection.close()

    def healthy(self) -> bool:
        with self._lock:
            try:
                self.connection.execute("SELECT 1")
            except psycopg.Error:
                self._connection.close()
                self.connection.execute("SELECT 1")
        return True

    def owns(self, subject: Subject, conversation_id: str) -> bool:
        with self._lock:
            return self.connection.execute(
                "SELECT 1 FROM conversations WHERE id = %s AND org_id = %s AND owner_id = %s",
                (conversation_id, subject.org_id, subject.user_id)).fetchone() is not None

    @contextmanager
    def hold_owned_source(self, subject: Subject, conversation_id: str):
        with self._lock, self.connection.transaction():
            owned = self.connection.execute(
                "SELECT 1 FROM conversations WHERE id = %s AND org_id = %s "
                "AND owner_id = %s FOR UPDATE",
                (conversation_id, subject.org_id, subject.user_id)).fetchone() is not None
            yield owned

    def owned_source_ids(self, subject: Subject, conversation_ids: set[str]) -> set[str]:
        if not conversation_ids:
            return set()
        if len(conversation_ids) > 100:
            raise ValueError("TOO_MANY_CONVERSATION_SOURCES")
        with self._lock:
            rows = self.connection.execute(
                "SELECT id FROM conversations WHERE org_id = %s AND owner_id = %s "
                "AND id = ANY(%s)",
                (subject.org_id, subject.user_id, list(conversation_ids))).fetchall()
        return {row["id"] for row in rows}

    def append(self, subject: Subject, conversation_id: str | None, question: str,
               mode: str, answer: dict, workflow_run_id: str | None = None,
               *, memory_include_ordinary: bool | None = None) -> str | None:
        now = _stamp(_now())
        with self._lock, self.connection.transaction():
            if workflow_run_id is not None:
                # Serialize repeat submissions from different API processes before
                # checking the unique workflow key. A collision only adds waiting.
                self.connection.execute(
                    "SELECT pg_advisory_xact_lock(hashtextextended(%s, 0))",
                    (workflow_run_id,))
                existing = self.connection.execute(
                    "SELECT c.id FROM conversation_turns t "
                    "JOIN conversations c ON c.id = t.conversation_id "
                    "WHERE t.workflow_run_id = %s AND c.org_id = %s AND c.owner_id = %s",
                    (workflow_run_id, subject.org_id, subject.user_id)).fetchone()
                if existing:
                    return existing["id"]
            if conversation_id is None:
                conversation_id = uuid4().hex
                self.connection.execute(
                    "INSERT INTO conversations VALUES (%s, %s, %s, %s, %s)",
                    (conversation_id, subject.org_id, subject.user_id, question[:80], now))
            else:
                owned = self.connection.execute(
                    "SELECT 1 FROM conversations WHERE id = %s AND org_id = %s "
                    "AND owner_id = %s FOR UPDATE",
                    (conversation_id, subject.org_id, subject.user_id)).fetchone()
                if owned is None:
                    return None
            turn = self.connection.execute(
                "INSERT INTO conversation_turns "
                "(conversation_id, question, mode, answer_json, workflow_run_id) "
                "VALUES (%s, %s, %s, %s, %s) RETURNING id",
                (conversation_id, question, mode,
                 json.dumps(answer, ensure_ascii=False), workflow_run_id)).fetchone()
            if memory_include_ordinary is not None and mode == "general":
                from app.api.memory_suggestions import eligible_auto_memory_text, eligible_user_text

                eligible = (eligible_auto_memory_text if memory_include_ordinary
                            else eligible_user_text)
                if eligible(question):
                    self.connection.execute(
                        "INSERT INTO conversation_memory_outbox "
                        "(id, org_id, owner_id, conversation_id, turn_id, "
                        "include_ordinary, created_at, available_at) "
                        "VALUES (%s, %s, %s, %s, %s, %s, %s, %s)",
                        (uuid4().hex, subject.org_id, subject.user_id, conversation_id,
                         turn["id"], int(memory_include_ordinary), now, now))
            self.connection.execute("UPDATE conversations SET updated_at = %s WHERE id = %s",
                                    (now, conversation_id))
        return conversation_id

    def list_for(self, subject: Subject) -> list[dict]:
        with self._lock:
            rows = self.connection.execute(
                "SELECT c.id, c.title, c.updated_at, COUNT(t.id) AS turn_count "
                "FROM conversations c LEFT JOIN conversation_turns t ON t.conversation_id = c.id "
                "WHERE c.org_id = %s AND c.owner_id = %s GROUP BY c.id "
                "ORDER BY c.updated_at DESC LIMIT 30",
                (subject.org_id, subject.user_id)).fetchall()
        return [dict(row) for row in rows]

    def _record_delete_event(self, subject: Subject, conversation_id: str) -> None:
        now = _stamp(_now())
        self.connection.execute(
            "INSERT INTO conversation_delete_outbox "
            "(id, org_id, owner_id, conversation_id, created_at, available_at) "
            "VALUES (%s, %s, %s, %s, %s, %s)",
            (uuid4().hex, subject.org_id, subject.user_id, conversation_id, now, now))

    def delete(self, subject: Subject, conversation_id: str) -> bool:
        with self._lock, self.connection.transaction():
            row = self.connection.execute(
                "SELECT 1 FROM conversations WHERE id = %s AND org_id = %s "
                "AND owner_id = %s FOR UPDATE",
                (conversation_id, subject.org_id, subject.user_id)).fetchone()
            if row is None:
                return False
            self.connection.execute(
                "DELETE FROM conversation_memory_outbox WHERE org_id = %s AND owner_id = %s "
                "AND conversation_id = %s",
                (subject.org_id, subject.user_id, conversation_id))
            self.connection.execute("DELETE FROM conversations WHERE id = %s", (conversation_id,))
            self._record_delete_event(subject, conversation_id)
        return True

    def conversation_for_run(self, subject: Subject, workflow_run_id: str) -> str | None:
        with self._lock:
            row = self.connection.execute(
                "SELECT c.id FROM conversation_turns t JOIN conversations c "
                "ON c.id = t.conversation_id WHERE t.workflow_run_id = %s "
                "AND c.org_id = %s AND c.owner_id = %s",
                (workflow_run_id, subject.org_id, subject.user_id)).fetchone()
        return row["id"] if row else None

    def merge(self, subject: Subject, target_id: str, source_id: str) -> bool:
        if target_id == source_id:
            return False
        with self._lock, self.connection.transaction():
            rows = self.connection.execute(
                "SELECT id FROM conversations WHERE id = ANY(%s) AND org_id = %s "
                "AND owner_id = %s ORDER BY id FOR UPDATE",
                ([target_id, source_id], subject.org_id, subject.user_id)).fetchall()
            if {row["id"] for row in rows} != {target_id, source_id}:
                return False
            self.connection.execute(
                "DELETE FROM conversation_memory_outbox WHERE org_id = %s AND owner_id = %s "
                "AND conversation_id = %s",
                (subject.org_id, subject.user_id, source_id))
            self.connection.execute(
                "UPDATE conversation_turns SET conversation_id = %s WHERE conversation_id = %s",
                (target_id, source_id))
            self.connection.execute("DELETE FROM conversations WHERE id = %s", (source_id,))
            self._record_delete_event(subject, source_id)
        return True

    def _claim(self, table: str, columns: str) -> dict | None:
        now = _now()
        now_text = _stamp(now)
        with self._lock, self.connection.transaction():
            self.connection.execute(
                sql.SQL("DELETE FROM {} WHERE delivered_at IS NOT NULL AND delivered_at < %s")
                .format(sql.Identifier(table)), (_stamp(now - timedelta(days=7)),))
            row = self.connection.execute(
                sql.SQL("SELECT {} FROM {} WHERE delivered_at IS NULL AND available_at <= %s "
                        "AND (lease_token IS NULL OR lease_until <= %s) "
                        "ORDER BY available_at, created_at, id LIMIT 1 FOR UPDATE SKIP LOCKED")
                .format(sql.SQL(columns), sql.Identifier(table)),
                (now_text, now_text)).fetchone()
            if row is None:
                return None
            token = uuid4().hex
            self.connection.execute(
                sql.SQL("UPDATE {} SET lease_token = %s, lease_until = %s, "
                        "attempts = attempts + 1 WHERE id = %s")
                .format(sql.Identifier(table)),
                (token, _stamp(now + timedelta(seconds=90)), row["id"]))
            return {**row, "attempts": row["attempts"] + 1, "lease_token": token}

    def claim_delete_event(self) -> dict | None:
        return self._claim("conversation_delete_outbox",
                           "id, org_id, owner_id, conversation_id, attempts")

    def claim_memory_event(self) -> dict | None:
        from app.api.memory_suggestions import eligible_auto_memory_text

        with self._lock, self.connection.transaction():
            event = self._claim("conversation_memory_outbox",
                                "id, org_id, owner_id, conversation_id, turn_id, "
                                "include_ordinary, attempts")
            if event is None:
                return None
            turn = self.connection.execute(
                "SELECT t.question FROM conversation_turns t JOIN conversations c "
                "ON c.id = t.conversation_id WHERE t.id = %s AND t.conversation_id = %s "
                "AND c.org_id = %s AND c.owner_id = %s",
                (event["turn_id"], event["conversation_id"], event["org_id"],
                 event["owner_id"])).fetchone()
            context = []
            if turn and event["include_ordinary"]:
                prior = self.connection.execute(
                    "SELECT question FROM conversation_turns WHERE conversation_id = %s "
                    "AND id < %s AND mode = 'general' ORDER BY id DESC",
                    (event["conversation_id"], event["turn_id"])).fetchall()
                for item in prior:
                    if eligible_auto_memory_text(item["question"]):
                        context.append(item["question"])
                        if len(context) == 3:
                            break
                context.reverse()
            return {**event, "question": turn["question"] if turn else None,
                    "context": tuple(context)}

    def _ack(self, table: str, event_id: str, lease_token: str) -> bool:
        now = _stamp(_now())
        with self._lock:
            result = self.connection.execute(
                sql.SQL("UPDATE {} SET delivered_at = %s, lease_token = NULL, "
                        "lease_until = NULL, last_error_code = NULL WHERE id = %s "
                        "AND lease_token = %s AND delivered_at IS NULL AND lease_until > %s")
                .format(sql.Identifier(table)), (now, event_id, lease_token, now))
            return result.rowcount == 1

    def ack_delete_event(self, event_id: str, lease_token: str) -> bool:
        return self._ack("conversation_delete_outbox", event_id, lease_token)

    def ack_memory_event(self, event_id: str, lease_token: str) -> bool:
        return self._ack("conversation_memory_outbox", event_id, lease_token)

    def _retry(self, table: str, event_id: str, lease_token: str,
               reason_code: str) -> bool:
        if reason_code not in ("target_unavailable", "target_error"):
            raise ValueError("INVALID_OUTBOX_REASON")
        now = _now()
        now_text = _stamp(now)
        with self._lock, self.connection.transaction():
            row = self.connection.execute(
                sql.SQL("SELECT attempts FROM {} WHERE id = %s AND lease_token = %s "
                        "AND delivered_at IS NULL AND lease_until > %s FOR UPDATE")
                .format(sql.Identifier(table)), (event_id, lease_token, now_text)).fetchone()
            if row is None:
                return False
            delay = min(300, 2 ** min(row["attempts"], 9))
            result = self.connection.execute(
                sql.SQL("UPDATE {} SET available_at = %s, lease_token = NULL, "
                        "lease_until = NULL, last_error_code = %s WHERE id = %s "
                        "AND lease_token = %s AND delivered_at IS NULL AND lease_until > %s")
                .format(sql.Identifier(table)),
                (_stamp(now + timedelta(seconds=delay)), reason_code,
                 event_id, lease_token, now_text))
            return result.rowcount == 1

    def retry_delete_event(self, event_id: str, lease_token: str, reason_code: str) -> bool:
        return self._retry("conversation_delete_outbox", event_id, lease_token, reason_code)

    def retry_memory_event(self, event_id: str, lease_token: str, reason_code: str) -> bool:
        return self._retry("conversation_memory_outbox", event_id, lease_token, reason_code)

    def _pending(self, table: str) -> int:
        with self._lock:
            return self.connection.execute(
                sql.SQL("SELECT count(*) AS count FROM {} WHERE delivered_at IS NULL")
                .format(sql.Identifier(table))).fetchone()["count"]

    def pending_delete_count(self) -> int:
        return self._pending("conversation_delete_outbox")

    def pending_memory_event_count(self) -> int:
        return self._pending("conversation_memory_outbox")

    def delete_outbox_metrics(self) -> dict:
        now = _now()
        with self._lock:
            row = self.connection.execute(
                "SELECT count(*) FILTER (WHERE delivered_at IS NULL) AS pending, "
                "count(*) FILTER (WHERE delivered_at IS NULL AND attempts > 1) AS retried, "
                "count(*) FILTER (WHERE delivered_at IS NULL AND last_error_code IS NOT NULL) "
                "AS failed_pending, "
                "count(*) FILTER (WHERE delivered_at IS NULL AND lease_token IS NOT NULL "
                "AND lease_until > %s) AS in_flight, "
                "count(*) FILTER (WHERE delivered_at >= %s) AS delivered_last_hour, "
                "min(created_at) FILTER (WHERE delivered_at IS NULL) AS oldest "
                "FROM conversation_delete_outbox",
                (_stamp(now), _stamp(now - timedelta(hours=1)))).fetchone()
        oldest = row["oldest"]
        return {"pending": row["pending"], "retried": row["retried"],
                "failed_pending": row["failed_pending"], "in_flight": row["in_flight"],
                "delivered_last_hour": row["delivered_last_hour"],
                "oldest_pending_seconds": max(0.0, (
                    now - datetime.fromisoformat(oldest)).total_seconds()) if oldest else None}

    def get(self, subject: Subject, conversation_id: str, documents: DocumentRepository,
            artifacts=None) -> dict | None:
        with self._lock:
            row = self.connection.execute(
                "SELECT * FROM conversations WHERE id = %s AND org_id = %s AND owner_id = %s",
                (conversation_id, subject.org_id, subject.user_id)).fetchone()
            if row is None:
                return None
            turns = self.connection.execute(
                "SELECT question, mode, answer_json FROM conversation_turns "
                "WHERE conversation_id = %s ORDER BY id LIMIT 100",
                (conversation_id,)).fetchall()
        return render_conversation(row, turns, subject, documents, artifacts)
